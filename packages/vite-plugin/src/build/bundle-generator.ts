import { existsSync } from "node:fs";
import { Registry } from "../core/registry";
import type { ServerEntry, WsEntry } from "../types";
import { createEndpointPaths, type EndpointPaths } from "../endpoint-paths";
import { toImportPath } from "../utils/path";
import {
  collectHandlerImports,
  emitApiDispatchRoute,
  emitHandlerDeclarations,
  emitServerHandlersMap,
  emitWsHandlersMap,
} from "./handler-emitter";

export function generateBundleContent(
  registry: Registry<ServerEntry>,
  serverEntry: string | undefined,
  serverEntryPath: string | null,
  serverOutDir: string,
  clientOutDir: string,
  port: number,
  wsRegistry?: Registry<WsEntry>,
  endpointPaths: EndpointPaths = createEndpointPaths(),
): string | null {
  const hasServerEntry = serverEntryPath ? existsSync(serverEntryPath) : false;
  const hasWs = !!wsRegistry && wsRegistry.size > 0;

  if (serverEntry && !hasServerEntry) {
    throw new Error(
      `[server-build] serverEntry '${serverEntry}' was configured but the file does not exist.`,
    );
  }

  if (!hasServerEntry && registry.size === 0 && !hasWs) return null;

  const serverImportPath = hasServerEntry
    ? toImportPath(serverOutDir, serverEntryPath!)
    : null;
  const clientRootRelativePath = toImportPath(serverOutDir, clientOutDir);

  // Server handlers from many source files are inlined into this single
  // module. Two files may legitimately use the same local name for different
  // imports, which would otherwise collide as duplicate top-level bindings.
  // Every distinct import gets a unique top-level alias and each handler
  // re-binds its own original local names through a small factory wrapper.
  const { importLines: serverImports, factoryArgsByEndpoint } =
    collectHandlerImports(registry, wsRegistry, serverOutDir);

  const lines: string[] = [
    "// Auto-generated by vite-plugin-server-sugar - do not edit",
    serverImportPath
      ? `import * as __serverEntry from '${serverImportPath}';`
      : "import { Hono } from 'hono';",
    "import { dirname, isAbsolute, join, relative, resolve } from 'path';",
    "import { fileURLToPath } from 'url';",
    ...serverImports,
    "",
  ];

  if (serverImportPath) {
    lines.push("const app = __serverEntry.default ?? __serverEntry.app;", "");
  } else {
    lines.push("const app = new Hono();", "");
  }

  if (serverImportPath) {
    lines.push(
      "if (!app || typeof app.fetch !== 'function') {",
      `  throw new Error("[server-build] ${serverEntry} must export a Hono app as default export or named 'app' export.");`,
      "}",
      "",
    );
  }

  if (hasWs) {
    lines.push(
      "// Tracks open sockets per ws() endpoint so a sibling",
      "// server()/ws() handler can broadcast via `<name>.send(data)`.",
      "const __wsConnections = new Map();",
      "function __sendWsPayload(ws, data) {",
      "  ws.send(JSON.stringify(data));",
      "}",
      "function __handleWsError(endpoint, phase, error, ws) {",
      "  console.error(`[server-build] Error in ws handler ${endpoint} (${phase}):`, error);",
      "  if (phase !== \"close\") ws.close(1011, \"Internal error\");",
      "}",
      "function __callWsHandler(endpoint, phase, ws, handler, ...args) {",
      "  if (!handler) return;",
      "  try {",
      "    Promise.resolve(handler(ws, ...args)).catch((error) => __handleWsError(endpoint, phase, error, ws));",
      "  } catch (error) {",
      "    __handleWsError(endpoint, phase, error, ws);",
      "  }",
      "}",
      "function __wrapWs(endpoint, handlers) {",
      "  return {",
      "    ...handlers,",
      "    send(data) {",
      "      const conns = __wsConnections.get(endpoint);",
      "      if (!conns) return;",
      "      for (const ws of conns) __sendWsPayload(ws, data);",
      "    },",
      "  };",
      "}",
      "",
    );
  }

  lines.push(
    ...emitHandlerDeclarations(registry, wsRegistry, factoryArgsByEndpoint),
  );

  lines.push(...emitServerHandlersMap(registry));

  if (hasWs) {
    lines.push(...emitWsHandlersMap(wsRegistry!));
  }

  lines.push(...emitApiDispatchRoute(endpointPaths.apiPrefix));

  lines.push(
    "// Serve static assets from the client build directory",
    "const __moduleUrl = import.meta.url;",
    'const __serverRoot = __moduleUrl.startsWith("file:") && !__moduleUrl.includes("$bunfs")',
    "  ? dirname(fileURLToPath(__moduleUrl))",
    "  : dirname(process.execPath);",
    `const __clientRoot = resolve(__serverRoot, ${JSON.stringify(clientRootRelativePath)});`,
    "",
    'app.use("*", async (c, next) => {',
    '  if (c.req.method !== "GET" && c.req.method !== "HEAD") {',
    "    return next();",
    "  }",
    "",
    "  const url = new URL(c.req.url);",
    "  let pathname;",
    "  try {",
    "    pathname = decodeURIComponent(url.pathname);",
    "  } catch {",
    '    return c.text("Bad request", 400);',
    "  }",
    '  const normalizedPathname = pathname.replace(/\\/+/g, "/");',
    '  const safePathname = normalizedPathname.startsWith("/") ? normalizedPathname : `/${normalizedPathname}`;',
    '  if (safePathname.includes("\\0")) {',
    '    return c.text("Bad request", 400);',
    "  }",
    "  const resolvedClientRoot = resolve(__clientRoot);",
    "  const filePath = resolve(resolvedClientRoot, `.${safePathname}`);",
    "  const relativePath = relative(resolvedClientRoot, filePath);",
    "",
    "  // Security: prevent directory traversal outside of the client build.",
    "  if (",
    '    relativePath === ".." ||',
    '    relativePath.startsWith("../") ||',
    '    relativePath.startsWith("..\\\\") ||',
    "    isAbsolute(relativePath)",
    "  ) {",
    '    return c.text("Not found", 404);',
    "  }",
    "",
    "  // Try to serve the exact file",
    '  if (!safePathname.endsWith("/")) {',
    "    const file = Bun.file(filePath);",
    "    if (await file.exists()) {",
    '      const cacheControl = safePathname.includes("/assets/")',
    '        ? "public, max-age=31536000, immutable"',
    '        : "public, max-age=0, must-revalidate";',
    '      return new Response(file, { headers: { "Cache-Control": cacheControl } });',
    "    }",
    "  }",
    "",
    "  return next();",
    "});",
    "",
    "// SPA fallback: serve index.html for any other GET requests",
    'app.get("*", async (c) => {',
    '  const index = Bun.file(join(__clientRoot, "index.html"));',
    "  if (await index.exists()) {",
    "    return new Response(index, {",
    '      headers: { "Content-Type": "text/html; charset=utf-8", "Cache-Control": "public, max-age=0, must-revalidate" },',
    "    });",
    "  }",
    "",
    '  return c.text("Not found", 404);',
    "});",
    "",
    "const __rawPort = Bun.env.PORT;",
    "const __parsedPort = __rawPort ? Number(__rawPort) : NaN;",
    `const PORT = Number.isInteger(__parsedPort) && __parsedPort >= 1 && __parsedPort <= 65535 ? __parsedPort : ${port};`,
    `if (__rawPort && PORT !== __parsedPort) console.warn(\`[server-build] Invalid PORT value "\${__rawPort}", falling back to ${port}\`);`,
    "",
  );

  if (hasWs) {
    lines.push(
      "Bun.serve({",
      "  port: PORT,",
      "  fetch(req, server) {",
      "    const __url = new URL(req.url);",
      `    if (__url.pathname.startsWith(${JSON.stringify(endpointPaths.wsPrefix)})) {`,
      "      let __endpoint;",
      "      try {",
      `        __endpoint = decodeURIComponent(__url.pathname.slice(${endpointPaths.wsPrefix.length}));`,
      "      } catch {",
      '        return new Response("Bad request", { status: 400 });',
      "      }",
      "      const __handlers = __wsHandlers[__endpoint];",
      "      if (!__handlers) {",
      '        return new Response("Not found", { status: 404 });',
      "      }",
      "      let __args = [];",
      "      try {",
      '        const __raw = __url.searchParams.get("args");',
      "        const __parsed = __raw ? JSON.parse(__raw) : [];",
      "        __args = Array.isArray(__parsed) ? __parsed : [__parsed];",
      "      } catch {}",
      "      const __upgraded = server.upgrade(req, { data: { endpoint: __endpoint, args: __args } });",
      "      if (__upgraded) return undefined;",
      '      return new Response("Upgrade failed", { status: 400 });',
      "    }",
      "    return app.fetch(req);",
      "  },",
      "  websocket: {",
      "    open(ws) {",
      "      ws.args = ws.data.args;",
      "      const __send = ws.send.bind(ws);",
      "      ws.send = (data) => __send(JSON.stringify(data));",
      "      let __conns = __wsConnections.get(ws.data.endpoint);",
      "      if (!__conns) {",
      "        __conns = new Set();",
      "        __wsConnections.set(ws.data.endpoint, __conns);",
      "      }",
      "      __conns.add(ws);",
      "      const __handlers = __wsHandlers[ws.data.endpoint];",
      "      __callWsHandler(ws.data.endpoint, \"open\", ws, __handlers?.onOpen);",
      "    },",
      "    message(ws, raw) {",
      "      let data;",
      "      try {",
      '        data = JSON.parse(typeof raw === "string" ? raw : raw.toString());',
      "      } catch {",
      "        data = raw;",
      "      }",
      "      const __handlers = __wsHandlers[ws.data.endpoint];",
      "      __callWsHandler(ws.data.endpoint, \"message\", ws, __handlers?.onMessage, data);",
      "    },",
      "    close(ws) {",
      "      const __conns = __wsConnections.get(ws.data.endpoint);",
      "      __conns?.delete(ws);",
      "      if (__conns?.size === 0) __wsConnections.delete(ws.data.endpoint);",
      "      const __handlers = __wsHandlers[ws.data.endpoint];",
      "      __callWsHandler(ws.data.endpoint, \"close\", ws, __handlers?.onClose);",
      "    },",
      "  },",
      "});",
      "",
      "console.log(`[server-build] Listening on http://localhost:${PORT}`);",
    );
  } else {
    lines.push(
      "Bun.serve({",
      "  port: PORT,",
      "  fetch: (req) => app.fetch(req),",
      "});",
      "",
      "console.log(`[server-build] Listening on http://localhost:${PORT}`);",
    );
  }

  return lines.join("\n");
}
