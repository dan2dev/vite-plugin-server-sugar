import { existsSync } from "node:fs";
import { Registry } from "../core/registry";
import type { ServerEntry, WsEntry } from "../types";
import { createEndpointPaths, type EndpointPaths } from "../endpoint-paths";
import { toImportPath } from "../utils/path";
import {
  collectHandlerImports,
  emitApiDispatchRoute,
  emitHandlerDeclarations,
  emitServerHandlersMap,
} from "./handler-emitter";
import {
  emitCloudflareContextHelper,
  emitCloudflareDispatch,
  emitCloudflareGatewayDispatch,
  type CloudflareGatewayRoute,
} from "./cloudflare-dispatch";
import { slugForEndpoints } from "./wrangler-config";

/**
 * Generated production output for `platform: "cloudflare-worker"`.
 *
 * Unlike the Bun + Hono generator, none of this code serves static assets or
 * calls a runtime-specific `serve()` — Cloudflare's own asset system handles
 * static files (see `wrangler-config.ts`), and a Worker module just exports
 * a `fetch`-compatible `default`. `$ws()` handlers are rejected outright: the
 * existing broadcast implementation relies on an in-memory `Map` that is not
 * safe across Cloudflare's stateless, recyclable isolates.
 *
 * No `serverEntry`: every `$server()`/HTTP endpoint is emitted as its own
 * independent Worker (`generateCloudflareFunctionBundles`), and the combined
 * Worker (`generateCloudflareWorkerBundle`) is a thin gateway that forwards
 * to them via Service Bindings instead of running handler code itself — see
 * `cloudflare-dispatch.ts`. `serverEntry` configured: no independent
 * Workers are generated at all, and the combined Worker mounts generated
 * endpoints onto the user's own Hono app instead, via the same Hono dispatch
 * route `platform: "hono"` uses — that's the user's choice by exporting a
 * Hono-compatible app, not this plugin's.
 */

function assertNoWebSockets(wsRegistry: Registry<WsEntry> | undefined): void {
  if (!wsRegistry || wsRegistry.size === 0) return;
  const endpoints = [...wsRegistry.values()].map((e) => e.endpoint).join(", ");
  throw new Error(
    `[server-build] platform: "cloudflare-worker" does not support $ws() endpoints (found: ${endpoints}). ` +
      "Cloudflare Workers needs Durable Objects to coordinate WebSocket connections across isolates, which " +
      'this plugin does not generate. Remove $ws() usage or use platform: "hono" instead.',
  );
}

const GENERATED_HEADER = "// Auto-generated by vite-plugin-server-sugar - do not edit";

/**
 * Generates the combined Cloudflare Worker module.
 *
 * With `serverEntry` configured, this mounts every `$server()`/HTTP endpoint
 * onto the user's own Hono app (same contract as the Bun + Hono output:
 * generated endpoints are registered on the user's app so its own
 * middleware also runs for them) and exports it directly.
 *
 * Without `serverEntry`, this does **not** run any handler code: it's a
 * thin gateway that forwards each endpoint to the independent Worker that
 * implements it, via the Service Bindings in `gatewayRoutes` (computed from
 * {@link generateCloudflareFunctionBundles}'s output — see
 * `plugin.ts`'s `writeCloudflareOutput`, which generates independent
 * Workers first so their names are known before building this).
 *
 * Returns `null` when there is nothing to generate, matching
 * {@link generateBundleContent}. Throws if `serverEntry` is configured but
 * missing, or if any `$ws()` endpoints are registered.
 */
export function generateCloudflareWorkerBundle(
  registry: Registry<ServerEntry>,
  serverEntry: string | undefined,
  serverEntryPath: string | null,
  serverOutDir: string,
  wsRegistry: Registry<WsEntry> | undefined,
  endpointPaths: EndpointPaths = createEndpointPaths(),
  gatewayRoutes: CloudflareGatewayRoute[] = [],
): string | null {
  assertNoWebSockets(wsRegistry);

  const hasServerEntry = serverEntryPath ? existsSync(serverEntryPath) : false;
  if (serverEntry && !hasServerEntry) {
    throw new Error(
      `[server-build] serverEntry '${serverEntry}' was configured but the file does not exist.`,
    );
  }
  if (!hasServerEntry && registry.size === 0) return null;

  if (hasServerEntry) {
    // A custom app is inherently a Hono app (see docs/configuration.md
    // #serverEntry) — mount generated endpoints on it exactly like
    // platform: "hono" does, reusing the same Hono dispatch route.
    const { importLines, factoryArgsByEndpoint } = collectHandlerImports(
      registry,
      undefined,
      serverOutDir,
    );
    const serverImportPath = toImportPath(serverOutDir, serverEntryPath!);
    const lines: string[] = [
      GENERATED_HEADER,
      `import * as __serverEntry from '${serverImportPath}';`,
      ...importLines,
      "",
      "const app = __serverEntry.default ?? __serverEntry.app;",
      "",
      "if (!app || typeof app.fetch !== 'function') {",
      `  throw new Error("[server-build] ${serverEntry} must export a Hono app as default export or named 'app' export.");`,
      "}",
      "",
    ];
    lines.push(...emitHandlerDeclarations(registry, undefined, factoryArgsByEndpoint));
    lines.push(...emitServerHandlersMap(registry));
    lines.push(...emitApiDispatchRoute(endpointPaths.apiPrefix));
    lines.push("export default app;", "");
    return lines.join("\n");
  }

  // No serverEntry: forward to the independent Workers instead of running
  // handler code here. No handler imports/declarations needed at all.
  return [
    GENERATED_HEADER,
    "",
    ...emitCloudflareGatewayDispatch(endpointPaths.apiPrefix, gatewayRoutes),
  ].join("\n");
}

export interface CloudflareFunctionBundle {
  /** Filesystem- and Worker-name-safe slug used for the output directory. */
  slug: string;
  /** Endpoint names served by this independent Worker. */
  endpoints: string[];
  /** Generated ES module source. */
  source: string;
}

/**
 * Generates one independent, fully self-contained Worker module per
 * `$server()`/HTTP endpoint so each can be deployed as its own Cloudflare
 * Worker — reachable directly, and (without `serverEntry`) also the actual
 * implementation the combined gateway Worker forwards to. Endpoints from the
 * same source file that share module-level state or reference each other by
 * their original name are grouped into a single Worker together, since that
 * state cannot be split across separately-deployed Workers.
 *
 * Returns an empty array when `serverEntry` is configured: generated
 * endpoints are mounted onto the user's app in the combined Worker instead
 * (see {@link generateCloudflareWorkerBundle}), so splitting them apart here
 * would silently skip the user's own middleware/routes for those endpoints.
 */
export function generateCloudflareFunctionBundles(
  registry: Registry<ServerEntry>,
  serverEntry: string | undefined,
  serverOutDir: string,
  wsRegistry?: Registry<WsEntry>,
  endpointPaths: EndpointPaths = createEndpointPaths(),
): CloudflareFunctionBundle[] {
  assertNoWebSockets(wsRegistry);

  if (serverEntry || registry.size === 0) return [];

  const entriesByFile = new Map<string, ServerEntry[]>();
  for (const entry of registry.values()) {
    const bucket = entriesByFile.get(entry.file);
    if (bucket) bucket.push(entry);
    else entriesByFile.set(entry.file, [entry]);
  }

  // Handlers that share module-level state or call each other by their
  // original name must stay in one Worker; everything else can split down
  // to one Worker per endpoint.
  const groups: ServerEntry[][] = [];
  for (const entries of entriesByFile.values()) {
    const useIIFE = !!entries[0]?.moduleDeclsJs || !!entries[0]?.hasSiblingCrossRefs;
    if (useIIFE) {
      groups.push(entries);
    } else {
      for (const entry of entries) groups.push([entry]);
    }
  }

  return groups.map((entries) => {
    const groupRegistry = new Registry<ServerEntry>();
    for (const entry of entries) groupRegistry.set(entry.endpoint, entry);

    const { importLines, factoryArgsByEndpoint } = collectHandlerImports(
      groupRegistry,
      undefined,
      serverOutDir,
    );

    const lines: string[] = [
      GENERATED_HEADER,
      ...importLines,
      "",
      ...emitHandlerDeclarations(groupRegistry, undefined, factoryArgsByEndpoint),
      ...emitServerHandlersMap(groupRegistry),
      ...emitCloudflareContextHelper(),
      ...emitCloudflareDispatch(endpointPaths.apiPrefix),
    ];

    const endpoints = entries.map((e) => e.endpoint);
    return { slug: slugForEndpoints(endpoints), endpoints, source: lines.join("\n") };
  });
}
